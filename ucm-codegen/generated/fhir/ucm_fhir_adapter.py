def _unwrap(value: Any) -> Any:
    return value["@value"] if isinstance(value, dict) and "@value" in value else value


def _iri(value: Any) -> Optional[str]:
    if isinstance(value, str):
        return value
    if isinstance(value, dict) and isinstance(value.get("@id"), str):
        return value["@id"]
    return None


def _values(node: Dict[str, Any], key: str) -> List[Any]:
    """Values under a term, its compact IRI or its full IRI"""
    for alias in KEYS.get(key, [key]):
        if alias in node:
            value = node[alias]
            return [_unwrap(v) for v in (value if isinstance(value, list) else [value])]
    return []


def _is_a(term: Optional[str], ancestor: str) -> bool:
    return term == ancestor or ancestor in ANCESTORS.get(term or "", [])


def _expand(value: str) -> str:
    if value in CONCEPTS:
        return CONCEPTS[value]
    prefix, _, local = value.partition(":")
    if local and prefix in PREFIXES and not local.startswith("//"):
        return PREFIXES[prefix] + local
    return value


def _set(target: Dict[str, Any], path: str, value: Any) -> None:
    *parents, last = path.split(".")
    for part in parents:
        target = target.setdefault(part, {})
    target[last] = value


def _get(source: Dict[str, Any], path: str) -> Any:
    for part in path.split("."):
        if not isinstance(source, dict):
            return None
        source = source.get(part)
    return source


def _node_iri_extension(element: Any) -> Optional[str]:
    if isinstance(element, dict):
        for ext in element.get("extension", []):
            if ext.get("url") == NODE_IRI_EXTENSION:
                return ext.get("valueUri")
    return None


class _Graph:
    def __init__(self, nodes: Iterable[Dict[str, Any]]):
        self.nodes = {n["@id"]: n for n in nodes if isinstance(n.get("@id"), str)}

    def node(self, item: Any) -> Optional[Dict[str, Any]]:
        if isinstance(item, dict) and set(item) - {"@id"}:
            return item
        iri = _iri(item)
        return self.nodes.get(iri) if iri else None

    def inverse(self, prop: str, iri: str) -> List[Dict[str, Any]]:
        return [n for _, n in sorted(self.nodes.items()) if iri in (_iri(v) for v in _values(n, prop))]

    def mapping_for(self, node: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        term = node.get("@type")
        for candidate in [term] + ANCESTORS.get(term or "", []):
            if candidate in MAPPINGS:
                return MAPPINGS[candidate]
        return None

    def role_terms(self, participation: Dict[str, Any]) -> List[str]:
        roles = (self.node(r) for r in _values(participation, "assumesRole"))
        return [r["@type"] for r in roles if r and "@type" in r]


