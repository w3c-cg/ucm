def _items(g: _Graph, node: Any, field: Dict[str, Any]) -> List[Tuple[Optional[Dict[str, Any]], Any]]:
    """(collected node, value) pairs for a field, relative to node"""
    start = g.node(node)
    if field["inverse"]:
        if start is None:
            return []
        collected = g.inverse(field["inverse"], start["@id"])
        if field["class"]:
            collected = [n for n in collected if _is_a(n.get("@type"), field["class"])]
        if field["roles"]:
            collected = [n for n in collected
                         if any(_is_a(r, role) for r in g.role_terms(n) for role in field["roles"])]
        if field["exclude_roles"]:
            collected = [n for n in collected
                         if not any(_is_a(r, role) for r in g.role_terms(n) for role in field["exclude_roles"])]
        pairs: List[Tuple[Optional[Dict[str, Any]], Any]] = [(n, n) for n in collected]
    else:
        pairs = [(None, node)]

    for hop in field["property"]:
        hopped = []
        for origin, value in pairs:
            current = g.node(value)
            if current is not None:
                hopped.extend((origin, v) for v in _values(current, hop))
        pairs = hopped
    return pairs


def _transform(g: _Graph, value: Any, field: Dict[str, Any]) -> Any:
    kind = field["transform"]
    if kind == "reference":
        iri = _iri(value)
        if iri is None:
            return None
        target = g.node(iri)
        if target is not None and g.mapping_for(target) is not None:
            return {"reference": full_url(iri)}
        return {"identifier": {"system": URI_SYSTEM, "value": iri}}
    if kind == "code":
        return field["map"].get(_expand(str(_iri(value) or value)))
    if kind == "class-coding":
        target = g.node(value)
        if target is None or "@type" not in target:
            return None
        return {"coding": [{"system": CODE_SYSTEM, "code": target["@type"]}]}
    if kind == "role-coding":
        iri = _iri(value)
        role = g.node(iri)
        concept: Dict[str, Any] = (
            {"coding": [{"system": CODE_SYSTEM, "code": role["@type"]}]} if role and "@type" in role
            else {"text": iri}
        )
        concept["extension"] = [{"url": NODE_IRI_EXTENSION, "valueUri": iri}]
        return concept
    if isinstance(value, dict):
        return None  # a node where a value was expected
    return value


def _tag(element: Any, origin: Optional[Dict[str, Any]]) -> Any:
    if origin is not None and isinstance(element, dict):
        element.setdefault("extension", []).append({"url": NODE_IRI_EXTENSION, "valueUri": origin["@id"]})
    return element


def _field(g: _Graph, node: Any, field: Dict[str, Any], warnings: List[str], where: str) -> Any:
    outputs = []
    for origin, value in _items(g, node, field):
        if "each" in field:
            element: Dict[str, Any] = {}
            for path, sub in field["each"].items():
                result = _field(g, value, sub, warnings, f"{where}.{path}")
                if result is not None:
                    _set(element, path, result)
            if element:
                outputs.append(_tag(element, origin if origin is not None else g.node(value)))
            continue
        result = _transform(g, value, field)
        if result is None:
            if field["transform"] == "code":
                warnings.append(f"{where}: {value!r} has no FHIR code in the mapping")
            continue
        outputs.append(_tag(result, origin))

    if not outputs and field.get("default") is not None:
        outputs = [field["default"]]
    if not outputs:
        return None
    return outputs[0] if field["single"] else outputs


def _resource_type(g: _Graph, node: Dict[str, Any], spec: Dict[str, Any]) -> str:
    participations = g.inverse("participatingEntity", node["@id"])
    for role, resource in spec["by_role"]:
        if any(_is_a(r, role) for p in participations for r in g.role_terms(p)):
            return resource
    return spec["resource"]


def to_fhir_bundle(nodes: Iterable[Dict[str, Any]]) -> Tuple[Dict[str, Any], List[str]]:
    """UCM nodes → FHIR collection Bundle; nodes of unmapped classes inform but are not emitted"""
    g = _Graph(nodes)
    warnings: List[str] = []
    entries = []
    for iri, node in sorted(g.nodes.items()):
        spec = g.mapping_for(node)
        if spec is None:
            continue
        meta: Dict[str, Any] = {"tag": [{"system": CODE_SYSTEM, "code": node["@type"]}]}
        if spec["profile"]:
            meta["profile"] = [spec["profile"]]
        resource: Dict[str, Any] = {
            "resourceType": _resource_type(g, node, spec),
            "id": resource_id(iri),
            "meta": meta,
            "identifier": [{"system": URI_SYSTEM, "value": iri}],
        }
        resource.update(copy.deepcopy(spec["constants"]))
        for path, field in spec["fields"].items():
            value = _field(g, node, field, warnings, f"{iri} {resource['resourceType']}.{path}")
            if value is not None:
                _set(resource, path, value)
        entries.append({"fullUrl": full_url(iri), "resource": resource})
    return {"resourceType": "Bundle", "type": "collection", "entry": entries}, warnings


