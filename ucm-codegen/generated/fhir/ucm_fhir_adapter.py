class _Nodes:
    def __init__(self) -> None:
        self.nodes: Dict[str, Dict[str, Any]] = {}

    def get(self, iri: str, type_: Optional[str] = None) -> Dict[str, Any]:
        node = self.nodes.setdefault(iri, {"@id": iri})
        if type_ and "@type" not in node:
            node["@type"] = type_
        return node

    @staticmethod
    def add(node: Dict[str, Any], term: str, value: Any) -> None:
        if SETS.get(term, True):
            values = node.setdefault(term, [])
            if value not in values:
                values.append(value)
        else:
            node[term] = value


def _reverse_value(field: Dict[str, Any], value: Any, urls: Dict[str, str], out: _Nodes) -> Any:
    kind = field["transform"]
    if kind == "reference":
        if not isinstance(value, dict):
            return None
        if value.get("reference") in urls:
            return urls[value["reference"]]
        identifier = value.get("identifier") or {}
        return identifier.get("value") if identifier.get("system") == URI_SYSTEM else None
    if kind == "code":
        return field["reverse"].get(value)
    if kind == "role-coding":
        iri = _node_iri_extension(value)
        codes = [c.get("code") for c in (value.get("coding") or [])] if isinstance(value, dict) else []
        if iri:
            out.get(iri, codes[0] if codes else None)
        return iri
    if kind == "class-coding":
        return None
    return value


def _reverse(field: Dict[str, Any], found: Any, current: Dict[str, Any], urls: Dict[str, str], out: _Nodes) -> None:
    if found is None or len(field["property"]) > 1:
        return  # absent, or a multi-hop path (one-way)
    prop = field["property"][0] if field["property"] else None
    for element in found if isinstance(found, list) else [found]:
        if "each" in field:
            child_iri = _node_iri_extension(element)
            if field["inverse"]:
                if child_iri is None:
                    continue
                child = out.get(child_iri, field["class"])
                out.add(child, field["inverse"], current["@id"])
                for path, sub in field["each"].items():
                    _reverse(sub, _get(element, path), child, urls, out)
            elif prop:
                for path, sub in field["each"].items():
                    if not sub["property"] and not sub["inverse"]:
                        value = _reverse_value(sub, _get(element, path), urls, out)
                        if value is not None:
                            out.add(current, prop, value)
            continue

        value = _reverse_value(field, element, urls, out)
        if value is None:
            continue
        if field["inverse"] and prop:
            child_iri = _node_iri_extension(element)
            if child_iri is not None:
                child = out.get(child_iri, field["class"])
                out.add(child, field["inverse"], current["@id"])
                out.add(child, prop, value)
        elif field["inverse"]:
            out.add(out.get(value), field["inverse"], current["@id"])
        elif prop:
            out.add(current, prop, value)


def from_fhir_bundle(bundle: Dict[str, Any]) -> List[Dict[str, Any]]:
    """FHIR Bundle (as produced by to_fhir_bundle) → UCM JSON-LD nodes"""
    urls: Dict[str, str] = {}
    for entry in bundle.get("entry", []):
        for identifier in entry["resource"].get("identifier", []):
            if identifier.get("system") == URI_SYSTEM:
                urls[entry["fullUrl"]] = identifier["value"]

    out = _Nodes()
    for entry in bundle.get("entry", []):
        resource = entry["resource"]
        iri = urls.get(entry.get("fullUrl", ""))
        tags = [t["code"] for t in resource.get("meta", {}).get("tag", []) if t.get("system") == CODE_SYSTEM]
        if iri is None or not tags:
            continue
        current = out.get(iri, tags[0])
        spec = next((MAPPINGS[c] for c in [tags[0]] + ANCESTORS.get(tags[0], []) if c in MAPPINGS), None)
        if spec is None:
            continue
        for path, field in spec["fields"].items():
            _reverse(field, _get(resource, path), current, urls, out)
    return [out.nodes[k] for k in sorted(out.nodes)]
