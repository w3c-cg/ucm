class _Nodes:
    def __init__(self) -> None:
        self.nodes: Dict[str, Dict[str, Any]] = {}

    def get(self, iri: str, type_: Optional[str] = None) -> Dict[str, Any]:
        node = self.nodes.setdefault(iri, {"@id": iri})
        if type_ and "@type" not in node:
            node["@type"] = type_
        return node

    @staticmethod
    def add(node: Dict[str, Any], term: str, value: Any) -> None:
        if SETS.get(term, True):
            values = node.setdefault(term, [])
            if value not in values:
                values.append(value)
        else:
            node[term] = value


def _reverse_value(field: Dict[str, Any], value: Any, urls: Dict[str, str], out: _Nodes,
                   ext: Any = None) -> Any:
    kind = field["transform"]
    if kind == "reference":
        if not isinstance(value, dict):
            return None
        if value.get("reference") in urls:
            return urls[value["reference"]]
        identifier = value.get("identifier") or {}
        return identifier.get("value") if identifier.get("system") == URI_SYSTEM else None
    if kind == "code":
        if field.get("system"):
            codes = [c.get("code") for c in (value.get("coding") or [])
                     if c.get("system") == field["system"]] if isinstance(value, dict) else []
            value = codes[0] if codes else None
        if value in (field.get("ambiguous") or []):
            iri = _node_iri_extension(ext)
            return CONCEPT_TERMS.get(iri) if iri else None
        return field["reverse"].get(value)
    if kind == "iri":
        return value if isinstance(value, str) else None
    if kind == "concept-coding":
        if not isinstance(value, dict):
            return None
        own = field.get("concepts")
        codings = [value] if field.get("coding") else (value.get("coding") or [])
        for coding in codings:
            code = coding.get("code")
            if code in CONCEPTS and coding.get("system") == concept_system(CONCEPTS[code]) and (own is None or code in own):
                return code
        if field.get("shared"):
            return None  # an adopter concept in a shared element: no way to tell whose it is
        return _node_iri_extension(value)
    if kind == "role-coding":
        iri = _node_iri_extension(value)
        codes = [c.get("code") for c in (value.get("coding") or [])] if isinstance(value, dict) else []
        if iri:
            out.get(iri, codes[0] if codes else None)
        return iri
    if kind == "class-coding":
        return None
    return value


def _matches(field: Dict[str, Any], element: Any) -> bool:
    return all(_get(element, k) == v for k, v in (field.get("when") or {}).items()) \
        if isinstance(element, dict) else not field.get("when")


def _reverse_fields(fields: Dict[str, Any], container: Dict[str, Any], current: Dict[str, Any],
                    urls: Dict[str, str], out: _Nodes) -> None:
    for key, field in fields.items():
        _reverse(field, _get(container, _base(key)), current, urls, out, _get(container, _ext_path(key)))


def _reverse(field: Dict[str, Any], found: Any, current: Dict[str, Any], urls: Dict[str, str], out: _Nodes,
             ext: Any = None) -> None:
    hops = field["property"]
    if found is None or field.get("one_way") or len(hops) > 2 or (len(hops) == 2 and field["inverse"]):
        return  # absent, one-way, or a path too long to rebuild
    prop = hops[0] if hops else None
    for element in found if isinstance(found, list) else [found]:
        if not _matches(field, element):
            continue
        if "each" in field:
            child_iri = _node_iri_extension(element)
            if field["inverse"]:
                if child_iri is None:
                    continue
                child = out.get(child_iri, field["class"])
                out.add(child, field["inverse"], current["@id"])
                _reverse_fields(field["each"], element, child, urls, out)
            elif prop and child_iri is not None and all(
                    sub["property"] or sub["inverse"] for sub in field["each"].values()):
                # the element stands for a node of its own (Consent.provision, provision.actor)
                child = out.get(child_iri, field["class"])
                out.add(current, prop, child_iri)
                _reverse_fields(field["each"], element, child, urls, out)
            elif prop:
                for path, sub in field["each"].items():
                    if not sub["property"] and not sub["inverse"]:
                        value = _reverse_value(sub, _get(element, _base(path)), urls, out)
                        if value is not None:
                            out.add(current, prop, value)
            continue

        value = _reverse_value(field, element, urls, out, ext)
        if value is None:
            continue
        if len(hops) == 2:
            middle = _node_iri_extension(element)
            if middle is not None:
                out.add(current, hops[0], middle)
                out.add(out.get(middle), hops[1], value)
        elif field["inverse"] and prop:
            child_iri = _node_iri_extension(element)
            if child_iri is not None:
                child = out.get(child_iri, field["class"])
                out.add(child, field["inverse"], current["@id"])
                out.add(child, prop, value)
        elif field["inverse"]:
            out.add(out.get(value), field["inverse"], current["@id"])
        elif prop:
            out.add(current, prop, value)


def from_fhir_bundle(bundle: Dict[str, Any]) -> List[Dict[str, Any]]:
    """FHIR Bundle (as produced by to_fhir_bundle) → UCM JSON-LD nodes"""
    urls: Dict[str, str] = {}
    for entry in bundle.get("entry", []):
        for identifier in entry["resource"].get("identifier", []):
            if identifier.get("system") == URI_SYSTEM:
                urls[entry["fullUrl"]] = identifier["value"]

    out = _Nodes()
    for entry in bundle.get("entry", []):
        resource = entry["resource"]
        iri = urls.get(entry.get("fullUrl", ""))
        tags = [t["code"] for t in resource.get("meta", {}).get("tag", []) if t.get("system") == CODE_SYSTEM]
        if iri is None or not tags:
            continue
        current = out.get(iri, tags[0])
        spec = next((MAPPINGS[c] for c in [tags[0]] + ANCESTORS.get(tags[0], []) if c in MAPPINGS), None)
        if spec is None:
            continue
        _reverse_fields(spec["fields"], resource, current, urls, out)
    return [out.nodes[k] for k in sorted(out.nodes)]
