def _items(g: _Graph, node: Any, field: Dict[str, Any]) -> List[Tuple[Optional[Dict[str, Any]], Any]]:
    """(collected node, value) pairs for a field, relative to node"""
    start = g.node(node)
    if field["inverse"]:
        if start is None:
            return []
        bases = [start]
        for hop in field.get("via") or []:
            bases = [n for b in bases for n in (g.node(v) for v in _values(b, hop)) if n is not None]
        collected, seen = [], set()
        for b in bases:
            for n in g.inverse(field["inverse"], b["@id"]):
                if n["@id"] not in seen:
                    seen.add(n["@id"])
                    collected.append(n)
        if field["class"]:
            collected = [n for n in collected if _is_a(n.get("@type"), field["class"])]
        if field["roles"]:
            collected = [n for n in collected
                         if any(_is_a(r, role) for r in g.role_terms(n) for role in field["roles"])]
        if field["exclude_roles"]:
            collected = [n for n in collected
                         if not any(_is_a(r, role) for r in g.role_terms(n) for role in field["exclude_roles"])]
        pairs: List[Tuple[Optional[Dict[str, Any]], Any]] = [(n, n) for n in collected]
    else:
        pairs = [(None, node)]

    two_hop = not field["inverse"] and len(field["property"]) == 2
    for i, hop in enumerate(field["property"]):
        hopped = []
        for origin, value in pairs:
            current = g.node(value)
            if current is not None:
                if two_hop and i == 1:
                    origin = current  # tag the value with the intermediate node
                hopped.extend((origin, v) for v in _values(current, hop))
        pairs = hopped
    return pairs


def _transform(g: _Graph, value: Any, field: Dict[str, Any]) -> Any:
    kind = field["transform"]
    if kind == "reference":
        iri = _iri(value)
        if iri is None:
            return None
        target = g.node(iri)
        if target is not None and g.mapping_for(target) is not None:
            return {"reference": full_url(iri)}
        return {"identifier": {"system": URI_SYSTEM, "value": iri}}
    if kind == "code":
        code = field["map"].get(_expand(str(_iri(value) or value)))
        if code is not None and field.get("system"):
            return {"coding": [{"system": field["system"], "code": code}]}
        return code
    if kind == "iri":
        return _iri(value)
    if kind == "concept-coding":
        iri = _expand(str(_iri(value) or value))
        if field.get("coding"):  # a bare Coding (Consent.provision.purpose, securityLabel)
            if iri in CONCEPT_TERMS:
                return {"system": concept_system(iri), "code": CONCEPT_TERMS[iri]}
            return {"display": iri, "extension": [{"url": NODE_IRI_EXTENSION, "valueUri": iri}]}
        if iri in CONCEPT_TERMS:
            return {"coding": [{"system": concept_system(iri), "code": CONCEPT_TERMS[iri]}]}
        # an adopter's own concept: keep its IRI so the reverse direction recovers it
        return {"text": iri, "extension": [{"url": NODE_IRI_EXTENSION, "valueUri": iri}]}
    if kind == "class-coding":
        target = g.node(value)
        term = _type_term(target.get("@type")) if target else None
        if term is None:
            return None
        return {"coding": [{"system": CODE_SYSTEM, "code": term}]}
    if kind == "role-coding":
        iri = _iri(value)
        role = g.node(iri)
        role_term = _type_term(role.get("@type")) if role else None
        concept: Dict[str, Any] = (
            {"coding": [{"system": CODE_SYSTEM, "code": role_term}]} if role_term is not None
            else {"text": iri}
        )
        concept["extension"] = [{"url": NODE_IRI_EXTENSION, "valueUri": iri}]
        return concept
    if isinstance(value, dict):
        return None  # a node where a value was expected
    return value


def _tag(element: Any, origin: Optional[Dict[str, Any]]) -> Any:
    if origin is not None and isinstance(element, dict):
        element.setdefault("extension", []).append({"url": NODE_IRI_EXTENSION, "valueUri": origin["@id"]})
    return element


def _fill(g: _Graph, node: Any, fields: Dict[str, Any], target: Dict[str, Any], warnings: List[str], where: str) -> None:
    """Write each field of a resource or backbone element into target"""
    for key, field in fields.items():
        value = _field(g, node, field, warnings, f"{where}.{_base(key)}")
        if value is None:
            continue
        _put(target, key, value)
        ext = _code_extension(g, node, field)
        if ext is not None:
            _set(target, _ext_path(key), ext)


def _code_extension(g: _Graph, node: Any, field: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """The exact UCM concept behind a code that several concepts share"""
    if field["transform"] != "code" or not field.get("ambiguous") or field.get("system"):
        return None
    for _, value in _items(g, node, field):
        iri = _expand(str(_iri(value) or value))
        if field["map"].get(iri) in field["ambiguous"]:
            return {"extension": [{"url": NODE_IRI_EXTENSION, "valueUri": iri}]}
    return None


def _field(g: _Graph, node: Any, field: Dict[str, Any], warnings: List[str], where: str) -> Any:
    outputs = []
    for origin, value in _items(g, node, field):
        if "each" in field:
            element: Dict[str, Any] = {}
            _fill(g, value, field["each"], element, warnings, where)
            if element:
                for path, constant in (field.get("when") or {}).items():
                    _set(element, path, constant)
                outputs.append(_tag(element, origin if origin is not None else g.node(value)))
            continue
        if field["transform"] == "reference" and field.get("resource_types"):
            target = g.node(value)
            spec = g.mapping_for(target) if target is not None else None
            kind = _resource_type(g, target, spec) if spec is not None else None
            if kind is not None and kind not in field["resource_types"]:
                warnings.append(f"{where}: {_iri(value)} maps to {kind}; FHIR R4 allows only "
                                f"{', '.join(field['resource_types'])} here")
                continue
        result = _transform(g, value, field)
        if result is None:
            if field["transform"] == "code":
                warnings.append(f"{where}: {value!r} has no FHIR code in the mapping")
            continue
        result = _tag(result, origin)
        if result not in outputs:
            outputs.append(result)

    if not outputs and field.get("default") is not None:
        outputs = [field["default"]]
    if not outputs:
        return None
    if field["single"] and len(outputs) > 1:
        warnings.append(f"{where}: FHIR allows one value here; kept the first of {len(outputs)}")
    return outputs[0] if field["single"] else outputs


def _resource_type(g: _Graph, node: Dict[str, Any], spec: Dict[str, Any]) -> str:
    participations = g.inverse("participatingEntity", node["@id"])
    for role, resource in spec["by_role"]:
        if any(_is_a(r, role) for p in participations for r in g.role_terms(p)):
            return resource
    return spec["resource"]


def to_fhir_bundle(nodes: Iterable[Dict[str, Any]]) -> Tuple[Dict[str, Any], List[str]]:
    """UCM nodes → FHIR collection Bundle; nodes of unmapped classes inform but are not emitted"""
    g = _Graph(nodes)
    warnings: List[str] = []
    entries = []
    for iri, node in sorted(g.nodes.items()):
        spec = g.mapping_for(node)
        if spec is None:
            continue
        meta: Dict[str, Any] = {"tag": [{"system": CODE_SYSTEM, "code": _type_term(node.get("@type"))}]}
        if spec["profile"]:
            meta["profile"] = [spec["profile"]]
        resource: Dict[str, Any] = {
            "resourceType": _resource_type(g, node, spec),
            "id": resource_id(iri),
            "meta": meta,
            "identifier": [{"system": URI_SYSTEM, "value": iri}],
        }
        resource.update(copy.deepcopy(spec["constants"]))
        _fill(g, node, spec["fields"], resource, warnings, f"{iri} {resource['resourceType']}")
        entries.append({"fullUrl": full_url(iri), "resource": resource})
    return {"resourceType": "Bundle", "type": "collection", "entry": entries}, warnings


